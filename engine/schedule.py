"""Printable weekly schedule for one warehouse (break-room posting)."""
from __future__ import annotations

import html

import pandas as pd

from .data import DEPT_NAMES, SHIFT_ORDER

DEPT_ORDER = {38: 1, 92: 2, 95: 3}


def _hhmm(t) -> str:
    return str(t)[:5] if isinstance(t, str) and t else ""


def posting_schedule(plan_scenario: pd.DataFrame, store: int) -> pd.DataFrame:
    """One row per day x department x shift for a warehouse, in reading order."""
    p = plan_scenario[plan_scenario.store_id == store].copy()
    p["_d"] = p.dept_id.map(DEPT_ORDER)
    p["_s"] = p.shift_code.map(SHIFT_ORDER)
    p = p.sort_values(["day_date", "_d", "_s"])
    rows = []
    for r in p.itertuples():
        closed = r.is_open == 0
        note = ""
        if not closed and r.rec_risk == "High":
            note = "AT RISK: pull cross-trained staff / overtime; escalate to GM if short"
        elif not closed and r.rec_risk == "Medium":
            note = "Watch: pre-approve one overtime backfill"
        rows.append({
            "Date": r.day_date, "Day": r.day_name, "Department": DEPT_NAMES[int(r.dept_id)], "Shift": r.shift_code,
            "Start": "" if closed else _hhmm(r.shift_start_time), "End": "" if closed else _hhmm(r.shift_end_time),
            "Staff": "Closed" if closed else int(r.recommended_employees),
            "Regular": "" if closed else int(r.rec_regular), "Borrowed": "" if closed else int(r.rec_flex),
            "Overtime": "" if closed else int(r.rec_ot), "Note": note,
        })
    return pd.DataFrame(rows)


def schedule_html(sched: pd.DataFrame, title: str, subtitle: str) -> str:
    """Self-contained printable HTML, one table per day, page break between days."""
    parts = [f"""<!doctype html><html><head><meta charset="utf-8"><title>{html.escape(title)}</title>
<style>
body {{ font-family: -apple-system, Segoe UI, Roboto, Arial, sans-serif; color: #111; margin: 24px; }}
h1 {{ font-size: 20px; margin: 0 0 4px; }} .sub {{ color: #555; margin-bottom: 16px; font-size: 13px; }}
h2 {{ font-size: 16px; margin: 20px 0 6px; }}
table {{ border-collapse: collapse; width: 100%; font-size: 13px; }}
th, td {{ border: 1px solid #bbb; padding: 5px 8px; text-align: left; }}
th {{ background: #eee; }} td.num {{ text-align: right; }} tr.closed td {{ color: #888; }}
td.note {{ color: #b71c1c; font-weight: 600; }}
.day {{ page-break-after: always; }} .day:last-child {{ page-break-after: auto; }}
@media print {{ body {{ margin: 10mm; }} }}
</style></head><body>
<h1>{html.escape(title)}</h1><div class="sub">{html.escape(subtitle)}</div>"""]
    for (date, day), g in sched.groupby(["Date", "Day"], sort=True):
        parts.append(f'<div class="day"><h2>{html.escape(day)} {html.escape(date)}</h2><table>'
                     "<tr><th>Department</th><th>Shift</th><th>Start</th><th>End</th><th>Staff</th>"
                     "<th>Regular</th><th>Borrowed</th><th>Overtime</th><th>Note</th></tr>")
        for r in g.itertuples():
            cls = ' class="closed"' if r.Staff == "Closed" else ""
            parts.append(f"<tr{cls}><td>{html.escape(r.Department)}</td><td>{r.Shift}</td><td>{r.Start}</td><td>{r.End}</td>"
                         f'<td class="num"><b>{r.Staff}</b></td><td class="num">{r.Regular}</td><td class="num">{r.Borrowed}</td>'
                         f'<td class="num">{r.Overtime}</td><td class="note">{html.escape(r.Note)}</td></tr>')
        parts.append("</table></div>")
    parts.append('<div class="sub">Generated by the Core 3 Staffing Planner · simulated case data</div></body></html>')
    return "".join(parts)
